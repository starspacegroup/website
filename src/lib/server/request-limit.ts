/** The client address, as far as Cloudflare will tell us. */
export function clientAddress(request: Request): string {
	return request.headers?.get('cf-connecting-ip') || request.headers?.get('x-real-ip') || 'unknown';
}

const core = RequestLimitCore.__default;
const big = (n: number) => new BigNumber(n);

/** The start (unix seconds) of the fixed window that `nowMs` falls in. */
export function windowStart(nowMs: number, windowSeconds: number): number {
	return core.WindowStart(big(Math.floor(nowMs / 1000)), big(windowSeconds)).toNumber();
}

/** Whether a window that has now been hit `hits` times is still within its limit. */
export function withinLimit(hits: number, max: number): boolean {
	return core.WithinLimit(big(hits), big(max));
}

/** Seconds until the window that refused a hit ends; 0 when allowed. */
export function retryAfter(
	hits: number,
	max: number,
	nowMs: number,
	windowSeconds: number
): number {
	return core
		.RetryAfter(big(hits), big(max), big(Math.floor(nowMs / 1000)), big(windowSeconds))
		.toNumber();
}

async function sha256(text: string): Promise<string> {
	const bytes = await crypto.subtle.digest('SHA-256', new TextEncoder().encode(text));
	return [...new Uint8Array(bytes)].map((b) => b.toString(16).padStart(2, '0')).join('');
}

export interface LimitResult {
	allowed: boolean;
	/** Seconds until the window that refused it ends (0 when allowed). */
	retryAfter: number;
}

/** The shape of a Workers Rate Limiting binding (`[[ratelimits]]`). */
export interface RateLimitBinding {
	limit(options: { key: string }): Promise<{ success: boolean }>;
}

/**
 * Count one hit against every limit given, and say whether all of them still allow
 * it. Every limit is counted even when an earlier one refuses, so a refused client
 * cannot keep the longer window empty.
 */
export async function hitLimits(
	db: D1Database | undefined,
	limits: readonly RequestLimit[],
	address: string,
	options: { nowMs?: number; binding?: RateLimitBinding } = {}
): Promise<LimitResult> {
	const nowMs = options.nowMs ?? Date.now();
	const scopes = limits.map((l) => l.scope).join(',');
	if (options.binding) {
		try {
			const { success } = await options.binding.limit({ key: `${scopes}:${address}` });
			if (!success) return { allowed: false, retryAfter: 60 };
		} catch (err) {
			console.error('rate limit binding unavailable, using the D1 window:', err);
		}
	}
	if (!db) return { allowed: true, retryAfter: 0 };
	try {
		const who = await sha256(address);
		let wait = 0;
		for (const limit of limits) {
			const start = windowStart(nowMs, limit.windowSeconds);
			const row = await db
				.prepare(
					`INSERT INTO request_limits (scope, who, window_start, hits) VALUES (?, ?, ?, 1)
					 ON CONFLICT (scope, who, window_start) DO UPDATE SET hits = hits + 1
					 RETURNING hits`
				)
				.bind(limit.scope, who, start)
				.first<{ hits: number }>();
			const hits = Number(row?.hits ?? 1);
			wait = core
				.CombineRetry(big(wait), big(retryAfter(hits, limit.max, nowMs, limit.windowSeconds)))
				.toNumber();
		}
		return { allowed: wait === 0, retryAfter: wait };
	} catch (err) {
		console.error('request limit unavailable, allowing the request:', err);
		return { allowed: true, retryAfter: 0 };
	}
}

/** Most old rows removed in one go: never an unbounded DELETE. */
const PRUNE_BATCH = 200;

/** Delete windows that ended more than two days ago. Safe to call often; never throws. */
export async function pruneLimits(db: D1Database, nowMs = Date.now()): Promise<void> {
	try {
		await db
			.prepare(
				`DELETE FROM request_limits WHERE (scope, who, window_start) IN (
					 SELECT scope, who, window_start FROM request_limits WHERE window_start < ? LIMIT ?
				 )`
			)
			.bind(Math.floor(nowMs / 1000) - 2 * 86_400, PRUNE_BATCH)
			.run();
	} catch {
		// old rows are only clutter
	}
}

/** What `limitRequest` needs from `event.platform`; structural so tests can pass a plain object. */
export interface LimitPlatform {
	env?: { DB?: unknown; REQUEST_RATE_LIMITER?: RateLimitBinding };
	context?: { waitUntil?: (promise: Promise<unknown>) => void };
}

/**
 * The one call a route makes: count this request's client address against
 * `limits` (D1, plus the optional REQUEST_RATE_LIMITER binding) and prune old
 * windows after the response. Allowed when there is no database.
 */
export async function limitRequest(
	platform: LimitPlatform | undefined,
	limits: readonly RequestLimit[],
	request: Request | undefined
): Promise<LimitResult> {
	const db = platform?.env?.DB as D1Database | undefined;
	const address = request?.headers ? clientAddress(request) : 'unknown';
	const result = await hitLimits(db, limits, address, {
		binding: platform?.env?.REQUEST_RATE_LIMITER
	});
	if (db) platform?.context?.waitUntil?.(pruneLimits(db));
	return result;
}

/** A 429 body and Retry-After header for a refused hit. */
export function tooManyRequests(result: LimitResult): Response {
	return new Response(JSON.stringify({ error: 'Too many requests. Try again later.' }), {
		status: 429,
		headers: {
			'content-type': 'application/json',
			'retry-after': String(Math.max(1, result.retryAfter))
		}
	});
}
