import type { D1Database } from '@cloudflare/workers-types';
import BigNumber from 'bignumber.js';
import { RequestLimitCore } from './generated/request-limit-core.js';

/**
 * A limit on how often one client address may do something costly.
 *
 * Ported from the Pinfool fork (29c7464 / 2086998 / 54209aa), where a script could
 * otherwise use up the day's database writes, Stripe sessions and email.
 *
 * Fixed windows, counted in D1 (KV allows only 1,000 writes a day on the free plan,
 * so it cannot hold counters). One statement per limit: it adds the hit and returns
 * the new count, so two requests at the same moment cannot both read "one left". The
 * address is stored only as a SHA-256.
 *
 * The decision rule (window start, within limit, retry-after, combining limits) is
 * proved in dafny/RequestLimit.dfy (WindowContainsNow, SameWindowSameRow,
 * RetryBounded, AtMostMaxPerWindow) and compiled to ./generated by
 * scripts/build-dafny.mjs. This file only moves values between D1 and the proved
 * functions.
 *
 * Optional fast path: when the platform has a Workers Rate Limiting binding
 * (`[[ratelimits]]`, e.g. `REQUEST_RATE_LIMITER`), pass it as `binding`; a refusal
 * there costs no D1 write at all. The D1 window is still the authority.
 *
 * This is a guard on cost, not an authorisation boundary: if the table cannot be
 * reached the request is allowed, because a broken counter must never stop a real
 * customer from paying.
 */
export interface RequestLimit {
	/** Names what is being limited; part of the row's key. */
	scope: string;
	/** Most hits allowed in one window. */
	max: number;
	windowSeconds: number;
}

