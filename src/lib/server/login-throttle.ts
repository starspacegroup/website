/**
 * A brake on password guessing.
 *
 * `/api/auth/login` is the first unauthenticated, unmetered, CPU-heavy endpoint in
 * the app: every attempt runs 100,000 rounds of PBKDF2 (the most Workers allows). Without a brake that is both
 * a credential-stuffing target and a way to spend our CPU budget for free, so the
 * two are counted together.
 *
 * Two counters, with two different limits. They are kept in D1 (`throttleStore`, at the end of
 * this file, migration 0018): the functions here were written against KV's `get`/`put`/`delete`,
 * and the store offers the same three calls, so the proved logic is unchanged. The account-merge
 * endpoint checks a password too, so it uses the same counters.
 *
 * - per client IP, `MAX_ATTEMPTS` (8) failures, any email. The window is refreshed on
 *   every failure, and a success does NOT clear it, so one address gets at most 8
 *   wrong guesses per window no matter how it interleaves logins to its own account.
 * - per email, `EMAIL_MAX_ATTEMPTS` (64) failures, any IP, in a FIXED window that
 *   starts at the first failure (the expiry is stored with the count and not moved).
 *   This is the brake on a distributed guesser aimed at one account.
 *
 * The email limit is 8 × the IP limit on purpose. Before 2026-11-04 both were 8, and
 * one attacker could lock any user out from anywhere by sending 8 wrong passwords for
 * their email (Lean counterexample `cx_lockout_from_other_ip`, NebulaKit/proofs).
 * Now one address can add at most 8 to an email's count per window, so locking out
 * an owner takes 8 addresses working together inside 15 minutes; the Lean model
 * proves a single address cannot (`single_ip_cannot_lock_out`). A success clears the
 * email counter, so the owner getting in resets the account's brake.
 *
 * This raises the cost of guessing, it is not an authorisation boundary, and it fails
 * *open* when the store is unavailable rather than locking everyone out of a working app.
 */

import type { D1Database, KVNamespace } from '@cloudflare/workers-types';
import BigNumber from 'bignumber.js';
import { LoginThrottleCore } from './generated/login-throttle-core.js';

// The decision rule is proved in dafny/LoginThrottle.dfy (SingleIpCannotLockOut, RunBounded,
// GoodPasswordOkUnlessThrottled) and compiled to ./generated by scripts/build-dafny.mjs.
// This file only moves values between KV and the proved functions.
const core = LoginThrottleCore.__default;
const big = (n: number) => new BigNumber(n);
const num = (b: BigNumber) => b.toNumber();

/** Failures tolerated per client address before its window closes. */
export const MAX_ATTEMPTS: number = num(core.MaxAttempts);

/** Failures tolerated per email, from all addresses together, per fixed window. */
export const EMAIL_MAX_ATTEMPTS: number = num(core.EmailMaxAttempts);

/** How long a failing identifier stays counted, in seconds. */
export const WINDOW_SECONDS: number = num(core.WindowSeconds);

function keyFor(scope: string, value: string): string {
	return `login_attempts:${scope}:${value.toLowerCase()}`;
}

/** The client address, as far as Cloudflare will tell us (one definition, shared with B5). */
export { clientAddress } from './request-limit';

/** `count` or `count:expiresAtEpochSeconds`. A bare count (older format) has no fixed expiry. */
function parse(raw: string | null): { count: number; expiresAt: number | null } {
	const [c, e] = (raw ?? '').split(':');
	const count = Number(c);
	const expiresAt = Number(e);
	return {
		count: Number.isInteger(count) && count > 0 ? count : 0,
		expiresAt: Number.isInteger(expiresAt) && expiresAt > 0 ? expiresAt : null
	};
}

async function read(kv: KVNamespace, key: string) {
	return parse(await kv.get(key));
}

const nowSeconds = () => Math.floor(Date.now() / 1000);

/**
 * Whether this attempt should be refused outright. Never throws: a KV outage must
 * not take login down with it.
 */
export async function isThrottled(
	kv: KVNamespace | undefined,
	ip: string,
	email: string,
	now: number = nowSeconds()
): Promise<boolean> {
	if (!kv) return false;
	try {
		const [byIp, byEmail] = await Promise.all([
			read(kv, keyFor('ip', ip)),
			read(kv, keyFor('email', email))
		]);
		return core.Throttled(
			big(byIp.count),
			big(byEmail.count),
			big(byEmail.expiresAt ?? 0),
			big(now)
		);
	} catch {
		return false;
	}
}

/** Record a failed attempt against both identifiers. */
export async function recordFailure(
	kv: KVNamespace | undefined,
	ip: string,
	email: string,
	now: number = nowSeconds()
): Promise<void> {
	if (!kv) return;
	try {
		await Promise.all([
			(async () => {
				// The IP window is refreshed on every failure, so sustained guessing from
				// one address keeps it shut rather than sliding out from under itself.
				const key = keyFor('ip', ip);
				const next = num(core.NextIpCount(big((await read(kv, key)).count)));
				await kv.put(key, String(next), { expirationTtl: WINDOW_SECONDS });
			})(),
			(async () => {
				// The email window is fixed at the first failure so it caps the DISTRIBUTED
				// rate at 64 failures per 15 min. (Single-IP safety does not depend on it:
				// Dafny's timed model shows a sliding window would also be single-IP safe.)
				const key = keyFor('email', email);
				const cur = await read(kv, key);
				const [count, expiresAt, t] = [big(cur.count), big(cur.expiresAt ?? 0), big(now)];
				const next = num(core.NextEmailCount(count, expiresAt, t));
				const nextExpiresAt = core.NextEmailExpiresAt(expiresAt, t);
				// KV refuses an absolute expiry under 60 s away; KvEmailExpiration keeps the floor.
				await kv.put(key, `${next}:${num(nextExpiresAt)}`, {
					expiration: num(core.KvEmailExpiration(nextExpiresAt, t))
				});
			})()
		]);
	} catch {
		// Best effort. A missed count is not worth failing the request over.
	}
}

/**
 * The account has just authenticated: forget its email counter. The address counter
 * is NOT cleared, so an attacker cannot reset its own budget by logging in to an
 * account it controls between guesses.
 */
export async function clearFailures(
	kv: KVNamespace | undefined,
	_ip: string,
	email: string
): Promise<void> {
	if (!kv) return;
	try {
		await kv.delete(keyFor('email', email));
	} catch {
		// Same: a stale counter expires on its own.
	}
}

/** Most expired counters removed in one go: never an unbounded DELETE. */
const PRUNE_BATCH = 100;

/**
 * The throttle's counters kept in D1 instead of KV, behind the same three calls the
 * functions above make (`get`, `put` with a TTL or an absolute expiry, `delete`), so
 * the proved logic is unchanged. Ported from the Pinfool fork (54209aa).
 *
 * Why: KV allows 1,000 writes a day on the free plan and each failed attempt writes
 * two counters, so one address failing on purpose could use the day's writes up,
 * after which the counters stopped rising and guessing was unlimited. D1 allows
 * 100,000 writes a day, and it is consistent at once, where KV let a spread-out
 * attacker squeeze in extra tries.
 */
export function throttleStore(db: D1Database | undefined): KVNamespace | undefined {
	if (!db) return undefined;
	const store = {
		async get(key: string): Promise<string | null> {
			const row = await db
				.prepare('SELECT value FROM login_throttle WHERE key = ? AND expires_at > ?')
				.bind(key, nowSeconds())
				.first<{ value: string }>();
			return row?.value ?? null;
		},
		async put(
			key: string,
			value: string,
			options: { expirationTtl?: number; expiration?: number } = {}
		): Promise<void> {
			const now = nowSeconds();
			const expiresAt = options.expiration ?? now + (options.expirationTtl ?? WINDOW_SECONDS);
			await db
				.prepare(
					`INSERT INTO login_throttle (key, value, expires_at) VALUES (?, ?, ?)
					 ON CONFLICT (key) DO UPDATE SET value = excluded.value, expires_at = excluded.expires_at`
				)
				.bind(key, value, expiresAt)
				.run();
			// Counters that ran out are cleared a few at a time as new ones are written.
			await db
				.prepare(
					`DELETE FROM login_throttle WHERE key IN (
						 SELECT key FROM login_throttle WHERE expires_at <= ? LIMIT ?
					 )`
				)
				.bind(now, PRUNE_BATCH)
				.run()
				.catch(() => undefined);
		},
		async delete(key: string): Promise<void> {
			await db.prepare('DELETE FROM login_throttle WHERE key = ?').bind(key).run();
		}
	};
	return store as unknown as KVNamespace;
}
