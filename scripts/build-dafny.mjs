// Verify each proved core in dafny/, compile it to JS, and wrap the CommonJS output as an ES
// module under src/lib/server/generated/. Needs `dafny` (4.11) on PATH.
//
//   dafny/LoginThrottle.dfy -> login-throttle-core.js  (LoginThrottleCore)
//   dafny/RequestLimit.dfy  -> request-limit-core.js   (RequestLimitCore)
//
// `node scripts/build-dafny.mjs RequestLimit` builds one.
import { execFileSync } from 'node:child_process';
import { mkdtempSync, readFileSync, writeFileSync, rmSync, mkdirSync } from 'node:fs';
import { join } from 'node:path';
import { homedir } from 'node:os';

const CORES = [
	{ dfy: 'LoginThrottle', out: 'login-throttle-core.js', module: 'LoginThrottleCore' },
	{ dfy: 'RequestLimit', out: 'request-limit-core.js', module: 'RequestLimitCore' }
];

const root = new URL('..', import.meta.url).pathname;
const only = process.argv[2];

for (const core of CORES.filter((c) => !only || c.dfy === only)) {
	const work = mkdtempSync(join(process.env.TMPDIR || join(homedir(), '.tmp'), 'dafny-'));
	try {
		execFileSync(
			'dafny',
			['build', '--target:js', join(root, `dafny/${core.dfy}.dfy`), '--output', join(work, 'out')],
			{
				stdio: ['ignore', 'inherit', 'inherit'],
				env: { ...process.env, NODE_PATH: join(root, 'node_modules') }
			}
		);
		const js = readFileSync(join(work, 'out.js'), 'utf8')
			.replace(
				"const BigNumber = require('bignumber.js');",
				"import BigNumber from 'bignumber.js';"
			)
			.replace(/\nlet _module = \(function\(\) \{[\s\S]*$/, '\n');
		if (js.includes('require(')) throw new Error('unexpected require() left in Dafny output');
		const out = join(root, 'src/lib/server/generated');
		mkdirSync(out, { recursive: true });
		writeFileSync(
			join(out, core.out),
			`// @ts-nocheck\n// GENERATED by scripts/build-dafny.mjs from dafny/${core.dfy}.dfy. Do not edit.\n${js}\nexport { _dafny, ${core.module} };\n`
		);
	} finally {
		rmSync(work, { recursive: true, force: true });
	}
}
